#!/usr/bin/env python3
"""
TPC-DS workloads for the materialization benchmark, generated by the
source-tpc-ds capture.

A scenario with a top-level `tpcds` block (instead of `collections` and
`transactions`) materializes the TPC-DS dataset at a scale factor:

    tpcds:
      scale: 1                  # source-tpc-ds scale factor (>= 0.01)
      transaction_size: 1GB     # commit after this many document bytes
      tables: [store_sales]     # optional subset; default: all 24
      resource: {delta_updates: true}   # optional, merged into every binding

The collections and their schemas come from the connector's own Discover, so
the materialization sees exactly what a production source-tpc-ds capture
would hand it. During the run `relay` drives the capture with
`flowctl raw preview-next`, copies its documents into the fixture FIFO and
writes a `{"commit": true}` after every `transaction_size` bytes of documents.
The capture's tables generate concurrently, so every transaction carries a mix
of tables. It stops once the capture checkpoints every binding as done.

With `--cache DIR` the fixture is generated once into DIR, keyed by the
workload and capture image, and later runs replay that file. Every connector
then sees the same transactions, and no capture competes with the
materialization for CPU while it is measured. `prepare` fills the cache
without feeding anything.

Subcommands (run.sh calls these; generate_spec.py imports the module):

    tpcds.py relay   --scenario S --source CAPTURE_SPEC --name TASK
                     --output FIFO --state STATE_JSON [--log PATH] [--cache DIR]
    tpcds.py prepare --scenario S --source CAPTURE_SPEC --name TASK
                     --cache DIR [--log PATH]
"""

import argparse
import hashlib
import json
import os
import shutil
import signal
import subprocess
import sys
from dataclasses import dataclass

import yaml

from generate import _maximize_pipe_buffer, parse_size

DEFAULT_IMAGE = "ghcr.io/estuary/source-tpc-ds:dev"
COLLECTION_PREFIX = "bench/tpcds/"


@dataclass
class Workload:
    scale: float
    transaction_size: int
    tables: list[str] | None
    resource: dict


def load(scenario: dict) -> Workload | None:
    """The scenario's TPC-DS workload, or None for a synthetic scenario."""
    raw = scenario.get("tpcds")
    if raw is None:
        return None
    if "collections" in scenario or "transactions" in scenario:
        raise ValueError("a tpcds scenario cannot also define collections or transactions")
    if "scale" not in raw:
        raise ValueError("tpcds.scale is required")
    if "transaction_size" not in raw:
        raise ValueError("tpcds.transaction_size is required")
    size = parse_size(raw["transaction_size"])
    if size <= 0:
        raise ValueError("tpcds.transaction_size must be positive")
    return Workload(
        scale=float(raw["scale"]),
        transaction_size=size,
        tables=raw.get("tables"),
        resource=dict(raw.get("resource") or {}),
    )


def image() -> str:
    return os.environ.get("TPCDS_IMAGE", DEFAULT_IMAGE)


def discover(workload: Workload) -> list[dict]:
    """The Discover bindings for the workload's tables, in discovery order."""
    request = json.dumps({"discover": {
        "connectorType": "IMAGE",
        "config": {"scale": workload.scale},
    }})
    result = subprocess.run(
        ["docker", "run", "--rm", "-i",
         "-e", "FLOW_RUNTIME_CODEC=json", "-e", "LOG_LEVEL=warn", image()],
        input=request + "\n", capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"source-tpc-ds discover failed:\n{result.stderr}")
    bindings = json.loads(result.stdout)["discovered"]["bindings"]

    if workload.tables is None:
        return bindings
    by_name = {b["recommendedName"]: b for b in bindings}
    unknown = [t for t in workload.tables if t not in by_name]
    if unknown:
        raise ValueError(f"unknown TPC-DS tables: {unknown}")
    return [by_name[t] for t in workload.tables]


def collection_name(table: str) -> str:
    return COLLECTION_PREFIX + table


def capture_spec(workload: Workload, bindings: list[dict], task: str) -> dict:
    """A flow spec holding the source-tpc-ds capture and its collections."""
    return {
        "collections": {
            collection_name(b["recommendedName"]): {
                "schema": b["documentSchema"],
                "key": b["key"],
            }
            for b in bindings
        },
        "captures": {
            task: {
                "endpoint": {"connector": {
                    "image": image(),
                    "config": {"scale": workload.scale},
                }},
                "bindings": [
                    {"resource": b["resourceConfig"],
                     "target": collection_name(b["recommendedName"])}
                    for b in bindings
                ],
            },
        },
    }


def relay(workload: Workload, source: str, task: str, output: str,
          state_path: str, log_path: str) -> int:
    with open(source) as f:
        spec = yaml.safe_load(f)
    pending = {b["resource"]["table"] for b in spec["captures"][task]["bindings"]}
    tables = sorted(pending)

    transactions = []
    totals = {t: {"docs": 0, "bytes": 0} for t in tables}
    tx_docs, tx_bytes, tx_tables = 0, 0, {}
    size = workload.transaction_size
    prefix_len = len(COLLECTION_PREFIX)

    def commit():
        nonlocal tx_docs, tx_bytes, tx_tables
        out.write(b'{"commit":true}\n')
        out.flush()
        transactions.append({
            "index": len(transactions),
            "collection": f"{len(tx_tables)} tables",
            "doc_count": tx_docs,
            "doc_size": tx_bytes // tx_docs,
            "bytes": tx_bytes,
            "tables": tx_tables,
        })
        tx_docs, tx_bytes, tx_tables = 0, 0, {}

    with open(log_path, "w") as log, subprocess.Popen(
        ["flowctl", "raw", "preview-next", "--source", source, "--name", task,
         "--output-state"],
        stdout=subprocess.PIPE, stderr=log, bufsize=1 << 20,
        # Its own process group, so stopping it reaches the connector too.
        start_new_session=True,
    ) as proc:
        def killed(signum, frame):
            os.killpg(proc.pid, signal.SIGKILL)
            sys.exit(128 + signum)
        handlers = {sig: signal.signal(sig, killed) for sig in (signal.SIGTERM, signal.SIGINT)}
        try:
            with open(output, "wb", buffering=1 << 20) as out:
                _maximize_pipe_buffer(out)
                # The leading empty commit applies the spec before data flows,
                # as in generate.py.
                out.write(b'{"commit":true}\n')
                for line in proc.stdout:
                    if line.startswith(b'["connectorState"'):
                        updated = json.loads(line)[1]["updated"].get("bindingStateV1", {})
                        for table, state in updated.items():
                            if state and state.get("done"):
                                pending.discard(table)
                        if not pending:
                            break
                        continue
                    # ["bench/tpcds/<table>",{...}]\n
                    end = line.index(b'"', 2)
                    table = line[2 + prefix_len:end].decode()
                    n = len(line) - end - 4
                    out.write(line)
                    t = totals[table]
                    t["docs"] += 1
                    t["bytes"] += n
                    tx_tables[table] = tx_tables.get(table, 0) + 1
                    tx_docs += 1
                    tx_bytes += n
                    if tx_bytes >= size:
                        commit()
                if tx_docs:
                    commit()
        finally:
            # The capture idles once it is done.
            if proc.poll() is None:
                os.killpg(proc.pid, signal.SIGTERM)
                try:
                    proc.wait(timeout=60)
                except subprocess.TimeoutExpired:
                    os.killpg(proc.pid, signal.SIGKILL)
            for sig, handler in handlers.items():
                signal.signal(sig, handler)

    complete = not pending
    with open(state_path, "w") as f:
        json.dump({
            "tpcds": {
                "scale": workload.scale,
                "transaction_size": size,
                "complete": complete,
                "tables": totals,
            },
            "transactions": transactions,
        }, f, indent=2)

    if not complete:
        print(f"capture exited (rc={proc.returncode}) before finishing: {sorted(pending)}; "
              f"see {log_path}", file=sys.stderr)
        return 1
    return 0


def cache_entry(workload: Workload, cache_dir: str) -> tuple[str, str]:
    """The fixture and state paths caching this workload's fixture."""
    identity = json.dumps([workload.scale, workload.transaction_size,
                           workload.tables, image()])
    digest = hashlib.sha256(identity.encode()).hexdigest()[:12]
    base = os.path.join(
        cache_dir, f"tpcds-scale-{workload.scale:g}-{workload.transaction_size}-{digest}")
    return base + ".jsonl", base + ".state.json"


def prepare(workload: Workload, source: str, task: str, cache_dir: str,
            log_path: str) -> int:
    fixture, state = cache_entry(workload, cache_dir)
    if os.path.exists(fixture) and os.path.exists(state):
        print(f"using cached fixture {fixture}", file=sys.stderr)
        return 0
    os.makedirs(cache_dir, exist_ok=True)
    print(f"generating fixture {fixture}", file=sys.stderr)
    rc = relay(workload, source, task, fixture + ".tmp", state + ".tmp", log_path)
    if rc != 0:
        return rc
    os.replace(fixture + ".tmp", fixture)
    os.replace(state + ".tmp", state)
    return 0


def replay(workload: Workload, cache_dir: str, output: str, state_path: str) -> int:
    fixture, state = cache_entry(workload, cache_dir)
    shutil.copyfile(state, state_path)
    with open(fixture, "rb") as src, open(output, "wb") as out:
        _maximize_pipe_buffer(out)
        shutil.copyfileobj(src, out, 1 << 20)
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    for name in ("relay", "prepare"):
        c = sub.add_parser(name)
        c.add_argument("--scenario", required=True)
        c.add_argument("--source", required=True, help="capture flow spec")
        c.add_argument("--name", required=True, help="capture task name")
        c.add_argument("--log", default=os.devnull, help="capture preview log")
        c.add_argument("--cache", default=None, required=name == "prepare",
                       help="fixture cache directory")
        if name == "relay":
            c.add_argument("--output", required=True, help="fixture path or FIFO")
            c.add_argument("--state", required=True, help="state JSON path")
    args = p.parse_args(argv)

    with open(args.scenario) as f:
        workload = load(yaml.safe_load(f))
    if workload is None:
        p.error(f"{args.scenario} has no tpcds block")

    if args.cache is None:
        return relay(workload, args.source, args.name, args.output, args.state, args.log)
    rc = prepare(workload, args.source, args.name, args.cache, args.log)
    if rc != 0 or args.command == "prepare":
        return rc
    return replay(workload, args.cache, args.output, args.state)

if __name__ == "__main__":
    sys.exit(main())
